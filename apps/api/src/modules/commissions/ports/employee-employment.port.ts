import type { Tx } from '@pospay/db';

import type { EmploymentDates } from '../domain/employment-overlap.ts';

/**
 * تواريخ عمل الموظفات التي يملكها staff، تُقرأ على معاملة الاعتماد نفسها (ADR-0010، قراءة دليل الموظفات).
 * يحتاجها الاعتماد في موضعين: من تدخل كشف الشهر بسطر EMPLOYEE بصفر، ومن لا يُرحَّل رصيدها مرة ثانية لأنها تركت العمل (D-22).
 * الاسم والرقم الوظيفي للعرض يأتيان من قراءة أخرى، فلا يختلطان هنا.
 */
export interface EmployeeEmploymentPort {
  /**
   * يعيد لكل موظفة تاريخ تعيينها ونهاية عقدها ويوم حذفها، بمن فيهن المحذوفات، لأن الموظفة التي تركت العمل هي بالتحديد
   * التي يحتاج الاعتماد معرفة أنها خرجت من الشهر قبل أن يقرر ترحيل رصيدها السالب مرة ثانية.
   * يوم الحذف يُحوَّل من لحظة الحذف إلى تاريخ النشاط المحلي داخل المحوّل، لأن الشهر شهر النشاط لا شهر UTC.
   * موظفة غير موجودة في الشركة أو النشاط لا تظهر في النتيجة، فلا تُعامَل كأنها عملت.
   *
   * @param tx معاملة الاعتماد نفسها، وبعد قفل الشهور لا قبله
   * @param companyId الشركة صاحبة الموظفات
   * @param businessId النشاط الذي يُحسب كشفه
   * @param employeeIds الموظفات المطلوبة، بلا تكرار
   * @returns خريطة من هوية الموظفة إلى تواريخ عملها
   */
  employmentDates(
    tx: Tx,
    companyId: string,
    businessId: string,
    employeeIds: readonly string[],
  ): Promise<ReadonlyMap<string, EmploymentDates>>;
}
