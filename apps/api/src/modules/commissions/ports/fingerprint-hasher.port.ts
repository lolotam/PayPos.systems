/**
 * تجزئة بصمات الكشف (D-6، D-26): الباني النقي بيطلّع قيمة JSON منظمة (نصوص وأعداد وقوائم وكائنات
 * بس، من غير bigint ولا تواريخ)، والتجزئة نفسها بتتم هنا برا الـ `domain/` لأن الاستخدام ممنوع
 * يستورد `@pospay/db` اللي فيه الترتيب الثابت للـ JSON.
 */
export interface FingerprintHasher {
  /**
   * بيرجّع بصمة القيمة: SHA-256 على تسلسلها الثابت (مفاتيح الكائن مرتبة، والقوائم بترتيبها)، بحروف
   * صغيرة hex بطول 64، وهي نفس صيغة أعمدة البصمة في `commission_statements`. نفس القيمة بتدّي
   * نفس البصمة مهما كان ترتيب بناء الكائن.
   *
   * @param value القيمة المنظمة اللي طلعت من الباني النقي
   * @returns البصمة بطول 64 حرف hex صغير
   */
  hash(value: unknown): string;
}
