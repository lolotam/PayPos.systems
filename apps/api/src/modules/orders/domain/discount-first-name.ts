/**
 * يقطع الاسم الأول من الاسم الكامل: أول كلمة بعد تجاهل المسافات.
 * القاعدة: القطع مرة واحدة عند الكتابة، والقوائم ما تقطعش في SQL (D-18).
 * الفصل على أي مسافة يونيكود (`\s`: مسافة، تاب، سطر جديد، NBSP، وباقي مسافات Zs، و U+FEFF).
 * اسم مالوش أي حرف غير مسافة يرجع كما هو، فالدالة كاملة وما بترميش.
 *
 * @param name الاسم الكامل كما جاء من قاعدة البيانات
 * @returns أول كلمة من الاسم، أو الاسم كما هو إن لم يكن فيه كلمة
 */
export function firstName(name: string): string {
  const first = name.split(/\s+/).find((word) => word.length > 0);
  return first ?? name;
}
