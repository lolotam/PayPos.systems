import { pushRecordStore } from './push-record-idb';

/**
 * بيقول إن السجل المحفوظ دلوقتي بتاع تسجيل تاني مش بتاع التسجيل اللي خسر المقارنة.
 * القاعدة: لو فيه سجل مخزن وتوكنه مختلف عن توكن التسجيل اللي بدأ، فالتسجيل التاني كسب
 * والمتصفح لازم يفضل معاه.
 *
 * السبب: المتصفح ماسك اشتراك push واحد بس، والسيرفر سطر واحد لكل تثبيت، فلو الخاسر شال
 * الاشتراك أو راجع السطر، بيقتل اشتراك اللي كسب. سطر السيرفر هيفضل عليه توكن الخاسر
 * لحد ما التحديث وقت الفتح يسجل توكن اللي كسب تاني، وحتى دلوقتي أي إشعار هيوري
 * إشعار محايد من غير نص (FR-014)، وده فشل آمن مش رسالة لحد تاني.
 * ولو مفيش سجل مخزن، أو التوكن المحفوظ هو نفسه توكن الخاسر (السجل اتعلق أو اتمسح أو
 * مراجعته اتزادت من دخول أو خروج أو إيقاف)، فتسجيل الخاسر مش مطلوب من حد، والتفكيك
 * القديم يفضل زي ما هو.
 *
 * @param expectedToken توكن التسجيل اللي خسر، أو null لو مفيش سجل كان موجود قبله
 * @returns true لو السجل المحفوظ بتاع تسجيل تاني، false لو مفيش سجل أو التوكن نفسه
 */
export async function newerRecordHoldsSubscription(expectedToken: string | null): Promise<boolean> {
  const record = await pushRecordStore.read().catch(() => null);
  if (record === null) return false;
  return record.token !== expectedToken;
}
