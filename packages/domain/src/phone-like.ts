// سبعة أرقام أو أكتر (أي نظام أرقام في Unicode: لاتيني أو عربي-هندي أو فارسي) يفصل بينهم مسافات أو شرط أو أقواس أو نقط أو +.
const PHONE_LIKE = /\p{Nd}(?:[\s().+-]*\p{Nd}){6,}/u;

/**
 * بيكشف أي رقم شكله رقم تليفون جوه نص حر قبل ما يتنسخ في إشعار أو حدث.
 * القاعدة نفسها بتاعة فحص أسماء العرض: سبعة أرقام أو أكتر متتابعة بأي فواصل،
 * بأي نظام أرقام، بمفتاح دولي أو من غيره. الأرقام القصيرة (زي "شيفت 3") مش بتتأثر.
 *
 * @param text النص الحر كما وصل
 * @returns true لو النص فيه رقم شكله رقم تليفون
 */
export function containsPhoneLikeNumber(text: string): boolean {
  return PHONE_LIKE.test(text.normalize('NFKC'));
}
