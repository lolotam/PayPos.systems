// كل الأسماء (العميل، الخدمة، التصنيف، نوع الباقة) بتستخدم النمط ده: يمنع حروف التحكم
// (Cc = U+0000–U+001F و U+007F–U+009F) من غير ما يستثني أي حرف تاني.
//
// النمط بينزل مع الـ OpenAPI كـ pattern، والـ \p{Cc} محتاج علم u اللي مفيش له مكان في JSON
// Schema فأي عميل مش JS بيقراه غلط؛ فبنكتبه بأرقام hex. وقاعدة no-control-regex بترفض أكواد
// C0 في الـ regex literal، وهي مش بتقدر تقرا قالب نصي — فالنمط مبني من قالب.
//
// مفيش lookahead في النمط: محركات RE2 (زي Go و Rust) مش بتعرف تترجم واحد. والـ $ في Python
// و Java بيقبل كمان السطر اللي قبل آخر سطر، فممكن العميل يقبل اسم بينتهي بسطر جديد؛
// السيرفر نفسه بيرفضه، فالنمط المنشور مش بيرفض أي اسم صح.
export const noControlChars = new RegExp(`^[^\\x00-\\x1F\\x7F-\\x9F]*$`);
