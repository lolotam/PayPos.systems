// Regenerates src/generated/{iso-4217,time-zones}.ts from the official sources, so validation is the
// same in Node and every browser instead of depending on each runtime's Intl data.
//   ISO 4217 — SIX (the ISO 4217 maintenance agency), list one
//   Time zones — IANA tzdb, every Zone and Link name in the main data files
// Run: pnpm --filter @pospay/contracts reference:update   (needs network and the `tar` command)
import { execFileSync } from 'node:child_process';
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

const ISO_URL =
  'https://www.six-group.com/dam/download/financial-information/data-center/iso-currrency/lists/list-one.xml';
const TZ_URL = 'https://data.iana.org/time-zones/tzdata-latest.tar.gz';
const TZ_FILES = [
  'africa',
  'antarctica',
  'asia',
  'australasia',
  'europe',
  'northamerica',
  'southamerica',
  'etcetera',
  'backward',
];
const out = (name) => new URL(`../src/generated/${name}`, import.meta.url);
const HEADER = '// Generated by scripts/update-reference-data.mjs — do not edit by hand.\n';

async function currencies() {
  const xml = await (await fetch(ISO_URL)).text();
  const published = /Pblshd="([^"]+)"/.exec(xml)?.[1];
  const units = new Map();
  for (const [, body] of xml.matchAll(/<CcyNtry>([\s\S]*?)<\/CcyNtry>/g)) {
    const code = /<Ccy>([A-Z]{3})<\/Ccy>/.exec(body)?.[1];
    const minor = /<CcyMnrUnts>(\d+)<\/CcyMnrUnts>/.exec(body)?.[1];
    if (code) units.set(code, minor === undefined ? null : Number(minor));
  }
  if (!published || units.size < 150)
    throw new Error('ISO 4217 list looks wrong — refusing to write');
  const rows = [...units].sort(([a], [b]) => a.localeCompare(b));
  writeFileSync(
    out('iso-4217.ts'),
    `${HEADER}// Source: SIX ISO 4217 list one, published ${published}. Minor units null = N.A. (e.g. XAU).\n` +
      `export const ISO_4217_PUBLISHED = '${published}';\n\n` +
      `export const ISO_4217_MINOR_UNITS: ReadonlyMap<string, number | null> = new Map([\n` +
      rows.map(([code, minor]) => `  ['${code}', ${minor}],`).join('\n') +
      `\n]);\n`,
  );
  return `${rows.length} currencies (${published})`;
}

async function timeZones() {
  const dir = mkdtempSync(join(tmpdir(), 'tzdb-'));
  try {
    const archive = join(dir, 'tzdata.tar.gz');
    writeFileSync(archive, Buffer.from(await (await fetch(TZ_URL)).arrayBuffer()));
    execFileSync('tar', ['-xzf', 'tzdata.tar.gz'], { cwd: dir });
    const version = readFileSync(join(dir, 'version'), 'utf8').trim();
    const names = new Set();
    for (const file of TZ_FILES) {
      for (const line of readFileSync(join(dir, file), 'utf8').split('\n')) {
        const fields = line.split(/\s+/);
        if (fields[0] === 'Zone') names.add(fields[1]);
        if (fields[0] === 'Link') names.add(fields[2]);
      }
    }
    if (names.size < 400) throw new Error('tzdb looks wrong — refusing to write');
    const sorted = [...names].sort();
    writeFileSync(
      out('time-zones.ts'),
      `${HEADER}// Source: IANA tzdb ${version} — every Zone and Link name.\n` +
        `export const TZDB_VERSION = '${version}';\n\n` +
        `export const TIME_ZONES: ReadonlySet<string> = new Set([\n` +
        sorted.map((name) => `  '${name}',`).join('\n') +
        `\n]);\n`,
    );
    return `${sorted.length} time zones (tzdb ${version})`;
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

console.log(await currencies());
console.log(await timeZones());
